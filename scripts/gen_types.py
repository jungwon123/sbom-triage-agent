#!/usr/bin/env python3
"""Generate web/src/lib/types.ts from the Pydantic models (CLAUDE.md rule 1).

usage: uv run python scripts/gen_types.py          # write
       uv run python scripts/gen_types.py --check  # exit 1 if the file is stale
"""
import pathlib
import sys

from triage import models

OUT = pathlib.Path(__file__).resolve().parents[1] / "web/src/lib/types.ts"
ROOTS = [models.CodeRef, models.Component, models.ServiceContext, models.Finding, models.RemediationProposal,
         models.AgentVerdict, models.Remediation, models.VerifyStep, models.Verification, models.Triage,
         models.Decision, models.Proposal, models.CombinedCheck, models.Job, models.Me]


def ts(s: dict) -> str:
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[1]
    if "enum" in s:
        return " | ".join(f'"{v}"' for v in s["enum"])
    if "const" in s:
        return f'"{s["const"]}"'
    if "anyOf" in s:
        return " | ".join(ts(x) for x in s["anyOf"])
    t = s.get("type")
    if t == "array":
        inner = ts(s.get("items", {}))
        return f"({inner})[]" if " | " in inner else f"{inner}[]"
    if t == "object":
        extra = s.get("additionalProperties")
        return f"Record<string, {ts(extra)}>" if isinstance(extra, dict) else "Record<string, unknown>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(t, "unknown")


def render() -> str:
    out = ["// Generated by scripts/gen_types.py from backend/triage/models.py. Do not edit by hand.", ""]
    done: set[str] = set()
    for model in ROOTS:
        schema = model.model_json_schema()
        for name, s in {**schema.get("$defs", {}), model.__name__: schema}.items():
            if name in done:
                continue
            done.add(name)
            if "enum" in s:
                out += [f"export type {name} = {ts(s)};", ""]
                continue
            out.append(f"export interface {name} {{")
            required = set(s.get("required", []))
            for field, fs in s.get("properties", {}).items():
                out.append(f"  {field}{'' if field in required else '?'}: {ts(fs)};")
            out += ["}", ""]
    return "\n".join(out)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        stale = not OUT.exists() or OUT.read_text() != text
        print("types.ts is stale: run scripts/gen_types.py" if stale else "types.ts is up to date")
        sys.exit(1 if stale else 0)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(OUT.parents[3])}")
